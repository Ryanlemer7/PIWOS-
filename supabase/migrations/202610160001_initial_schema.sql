-- OWO initial schema. Apply with Supabase CLI or SQL Editor after reviewing.
-- Tenant isolation is enforced in PostgreSQL with RLS; client-side filters are not security.
create extension if not exists pgcrypto;

create type public.company_member_role as enum ('owner', 'admin', 'manager', 'staff', 'viewer');
create type public.order_status as enum ('pending', 'confirmed', 'preparing', 'shipped', 'completed', 'cancelled');
create type public.post_reaction as enum ('like', 'dislike');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.companies (
  id uuid primary key default gen_random_uuid(),
  legal_name text not null,
  public_name text not null,
  company_code text not null unique default upper(encode(gen_random_bytes(6), 'hex')),
  registration_country text,
  registration_number text,
  contact_email text,
  description text,
  logo_url text,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.company_members (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.company_member_role not null default 'staff',
  joined_at timestamptz not null default now(),
  unique(company_id, user_id)
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  name text not null,
  description text,
  category text,
  price_amount numeric(18, 4) not null check (price_amount >= 0),
  price_currency text not null default 'PI',
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  image_url text,
  is_published boolean not null default false,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  order_number bigint generated by default as identity,
  customer_user_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  status public.order_status not null default 'pending',
  currency text not null default 'PI',
  total_amount numeric(18, 4) not null default 0 check (total_amount >= 0),
  notes text,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(company_id, order_number)
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(18, 4) not null check (unit_price >= 0),
  created_at timestamptz not null default now()
);

create table public.showcase_posts (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  author_id uuid not null default auth.uid() references auth.users(id),
  body text not null check (char_length(trim(body)) > 0),
  media_url text,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.post_reactions (
  id uuid primary key default gen_random_uuid(),
  post_id uuid not null references public.showcase_posts(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  reaction public.post_reaction not null,
  reason text,
  created_at timestamptz not null default now(),
  unique(post_id, user_id),
  constraint dislike_requires_reason check (
    (reaction = 'like' and (reason is null or char_length(trim(reason)) = 0))
    or (reaction = 'dislike' and char_length(trim(coalesce(reason, ''))) >= 20)
  )
);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  company_id uuid references public.companies(id) on delete cascade,
  sender_id uuid not null default auth.uid() references auth.users(id),
  recipient_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(trim(body)) > 0),
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  company_id uuid references public.companies(id) on delete cascade,
  title text not null,
  body text,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

-- Internal bookkeeping records only: this table is not a bank account or a payment rail.
create table public.ledger_entries (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  entry_type text not null check (entry_type in ('credit', 'debit', 'adjustment')),
  amount numeric(18, 4) not null check (amount > 0),
  currency text not null default 'PI',
  description text not null,
  reference text,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now()
);

create table public.legal_documents (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  title text not null,
  document_type text not null default 'other',
  storage_path text,
  status text not null default 'draft' check (status in ('draft', 'review', 'signed', 'archived')),
  due_at timestamptz,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Append-only audit log. Application users can insert their own events, but cannot update/delete.
create table public.audit_events (
  id bigint generated always as identity primary key,
  company_id uuid references public.companies(id) on delete set null,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index products_company_published_idx on public.products(company_id, is_published, created_at desc);
create index orders_company_status_idx on public.orders(company_id, status, created_at desc);
create index showcase_company_published_idx on public.showcase_posts(company_id, is_published, created_at desc);
create index messages_participants_created_idx on public.messages(sender_id, recipient_id, created_at desc);
create index notifications_user_unread_idx on public.notifications(user_id, created_at desc) where read_at is null;
create index audit_company_created_idx on public.audit_events(company_id, created_at desc);
create index members_user_idx on public.company_members(user_id, company_id);

create or replace function public.is_company_member(target_company uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.company_members m
    where m.company_id = target_company and m.user_id = auth.uid()
  );
$$;

create or replace function public.has_company_role(target_company uuid, allowed_roles public.company_member_role[])
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.company_members m
    where m.company_id = target_company
      and m.user_id = auth.uid()
      and m.role = any(allowed_roles)
  );
$$;

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

